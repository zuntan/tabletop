import { test } from 'node:test';
import assert from 'node:assert/strict';
import { openTestDesk } from './desk-browser';

test('sidebar tabs use full height, preserve tab/scroll and hide without changing desk state', { timeout: 45_000 }, async () => {
  const { page, call, close, errors } = await openTestDesk('sidebar-test');
  try {
    assert.equal(await page.getByRole('tab').count(), 4);
    assert.equal(await page.locator('#object-filter').isVisible(), false);
    assert.equal(await page.locator('#object-filter').evaluate(element => getComputedStyle(element).display), 'none');
    assert.deepEqual(await page.locator('.sidebar-panel').evaluateAll(elements => elements.map(element => getComputedStyle(element).paddingBottom)), ['72px', '72px', '72px', '72px']);
    const actionButtons = '#property-lock, #property-lock-mixed, #series-fit, #connect-form > button[type="submit"], #handoff-start, #handoff-hide';
    assert.deepEqual(await page.locator(actionButtons).evaluateAll(buttons => buttons.map(button => getComputedStyle(button).fontSize)), Array(6).fill('10px'));
    assert.equal(await page.locator('.property-lock-control').evaluate(element => getComputedStyle(element).marginTop), '8px');
    assert.equal(await page.locator('.property-lock-control').evaluate(element => getComputedStyle(element).marginBottom), '4px');
    assert.deepEqual(await page.locator('#property-lock, #property-lock-mixed').evaluateAll(buttons => buttons.map(button => getComputedStyle(button).height)), ['32px', '32px']);
    assert.equal(await page.locator('#tab-properties').evaluate(button => getComputedStyle(button).fontSize), '10px');
    assert.equal(await page.locator('header #sidebar-toggle').count(), 0);
    assert.equal(await page.locator('.sidebar-heading > #sidebar-toggle').count(), 1);
    assert.equal(await page.locator('[role="tablist"] #sidebar-toggle').count(), 0);
    const toggleBounds = (await page.locator('#sidebar-toggle').boundingBox())!;
    const tabsBounds = (await page.locator('.sidebar-tabs').boundingBox())!;
    assert.ok(toggleBounds.x >= tabsBounds.x + tabsBounds.width);
    assert.ok(Math.abs(toggleBounds.y + toggleBounds.height / 2 - (tabsBounds.y + tabsBounds.height / 2)) < 2);
    assert.equal(await page.locator('#tab-properties').getAttribute('aria-selected'), 'true');
    for (let i = 0; i < 55; i++) await call('desk_execute', { operations: [{ kind: 'add', object: { id: `object-${i}`, type: 'rect', x: i * 10, y: i * 5, text: `Object ${i}` } }] });
    await page.locator('#tab-history').click();
    assert.equal(await page.locator('#history .history-row').count(), 50);
    const panel = page.locator('#panel-history');
    const dimensions = await panel.evaluate(element => ({ height: element.clientHeight, scroll: element.scrollHeight, aside: element.parentElement!.parentElement!.clientHeight }));
    assert.ok(dimensions.height > dimensions.aside - 65); assert.ok(dimensions.scroll > dimensions.height);
    await panel.evaluate(element => { element.scrollTop = 200; });
    const state = await call('desk_state'); const width = (await page.locator('#canvas').boundingBox())!.width;
    await page.locator('#sidebar-toggle').click();
    assert.equal(await page.locator('#sidebar').isVisible(), false);
    const canvasBounds = (await page.locator('#canvas').boundingBox())!;
    const floatingBounds = (await page.locator('#sidebar-toggle').boundingBox())!;
    assert.ok(canvasBounds.width > width);
    assert.equal(await page.locator('#workspace > #sidebar-toggle').count(), 1);
    assert.ok(Math.abs(floatingBounds.x + floatingBounds.width - (canvasBounds.x + canvasBounds.width - 8)) < 2);
    assert.ok(Math.abs(floatingBounds.y - canvasBounds.y - 8) < 2);
    assert.equal(await page.locator('#sidebar-toggle').getAttribute('aria-expanded'), 'false');
    assert.equal(await page.locator('#sidebar-toggle').evaluate(element => document.activeElement === element), true);
    assert.deepEqual(await call('desk_state'), state);
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('.sidebar-heading > #sidebar-toggle').count(), 1);
    assert.equal(await page.locator('#tab-history').getAttribute('aria-selected'), 'true');
    assert.equal(await panel.evaluate(element => element.scrollTop), 200);
    await page.locator('#tab-objects').click();
    assert.equal(await page.locator('#object-filter').isVisible(), true);
    assert.equal(await page.locator('#object-filter-apply').getAttribute('aria-checked'), 'false');
    assert.equal(await page.locator('#object-filter-apply .thinking-switch-state').textContent(), 'OFF');
    assert.deepEqual(await page.locator('.object-filter-categories button').allTextContents(), ['クリアファイル', 'クリップ', 'ピン', 'カード', '図形', '線', '画像', 'その他']);
    assert.deepEqual(await page.locator('.object-filter-categories button').evaluateAll(buttons => buttons.map(button => button.getAttribute('aria-pressed'))), ['false', 'false', 'true', 'false', 'false', 'false', 'false', 'false']);
    const categoryBounds = await page.locator('.object-filter-categories button').evaluateAll(buttons => buttons.map(button => button.getBoundingClientRect().toJSON()));
    assert.ok(categoryBounds.slice(0,4).every(bounds => Math.abs(bounds.y - categoryBounds[0].y) < 1));
    assert.ok(categoryBounds.slice(4).every(bounds => Math.abs(bounds.y - categoryBounds[4].y) < 1));
    assert.ok(categoryBounds[4].y > categoryBounds[0].y + categoryBounds[0].height);
    const applyBounds = (await page.locator('#object-filter-apply').boundingBox())!;
    const bulkBounds = (await page.locator('.object-filter-bulk-actions').boundingBox())!;
    assert.ok(bulkBounds.x >= applyBounds.x + applyBounds.width);
    assert.ok(Math.abs(bulkBounds.y + bulkBounds.height / 2 - (applyBounds.y + applyBounds.height / 2)) < 1);
    await page.locator('#object-filter-apply').click();
    assert.equal(await page.locator('#object-filter-apply').getAttribute('aria-checked'), 'true');
    await page.locator('#object-filter-pins').click();
    assert.equal(await page.locator('#object-filter-pins').getAttribute('aria-pressed'), 'false');
    await page.locator('#object-filter-pins').click();
    await page.locator('#object-filter-apply').click();
    assert.equal(await page.locator('#object-filter-apply').getAttribute('aria-checked'), 'false');
    assert.equal(await page.locator('#object-filter').evaluate(element => element.parentElement?.id), 'sidebar');
    const filterBounds = (await page.locator('#object-filter').boundingBox())!;
    const objectsPanelBounds = (await page.locator('#panel-objects').boundingBox())!;
    assert.ok(filterBounds.y + filterBounds.height <= objectsPanelBounds.y);
    assert.equal(await page.locator('#tab-objects').textContent(), 'オブジェクト');
    assert.equal(await page.locator('#panel-objects h2').evaluate(element => element.firstChild?.textContent?.trim()), 'オブジェクトリスト');
    assert.equal(await page.locator('#object-list .object-row').count(), 55);
    assert.equal(await page.locator('#object-list').evaluate(element => getComputedStyle(element).maxHeight), 'none');
    await page.locator('#tab-objects').focus(); await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#tab-history').getAttribute('aria-selected'), 'true');
    assert.equal(await page.locator('#object-filter').isVisible(), false);
    await page.keyboard.press('End'); assert.equal(await page.locator('#tab-connection').getAttribute('aria-selected'), 'true');
    assert.equal(await page.locator('#connect-form').isVisible(), true);
    await page.keyboard.press('Home'); assert.equal(await page.locator('#tab-properties').getAttribute('aria-selected'), 'true');
    await call('desk_execute', { operations: [{ kind: 'label_add', id: 'sidebar-pin', seriesId: 'series-1', x: 120, y: 120 }] });
    await call('desk_select', { ids: ['sidebar-pin'] });
    assert.equal(await page.locator('#series-panel').isVisible(), true);
    await page.locator('#numbering-settings').click();
    assert.equal(await page.locator('#series-panel').isVisible(), false);
    await page.locator('#tab-history').click(); await page.locator('#sidebar-toggle').click();
    await page.locator('#numbering-settings').click();
    assert.equal(await page.locator('#sidebar').isVisible(), true);
    assert.equal(await page.locator('#series-panel').isVisible(), true);
    assert.equal(await page.locator('#series-panel h2').textContent(), 'ピンシリーズ');
    assert.equal(await page.locator('#panel-properties').evaluate(panel => panel.firstElementChild?.classList.contains('property-lock-control')), true);
    await page.setViewportSize({ width: 390, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.locator('#sidebar-toggle').click(); assert.equal(await page.locator('#sidebar').isVisible(), false);
    assert.deepEqual(errors, []);
  } finally { await close(); }
});
